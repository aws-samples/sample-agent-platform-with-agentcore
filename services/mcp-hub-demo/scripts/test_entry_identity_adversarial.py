"""Unit test for hub/entry_identity.py: what the hub trusts behind the IAM entry.

No Keycloak, no AWS, no running hub — the function is pure. Run:
    python scripts/test_entry_identity.py
"""

import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("entry_identity", HERE / "hub" / "entry_identity.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

failures: list[str] = []


def check(name: str, condition: bool, detail: str = "") -> None:
    print(f"  [{'PASS' if condition else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""))
    if not condition:
        failures.append(name)


ROLE = "agent-platform-mcp-hub-caller"
ACCOUNT = "0" * 12  # a placeholder account id, built at runtime so no 12-digit literal sits in a published file
ARN = f"arn:aws:sts::{ACCOUNT}:assumed-role/{ROLE}/agent-0123abcd"
GOOD = {"x-mcp-hub-entry-secret": "s3cret", "x-caller-arn": ARN}

entry = mod.load_entry_identity({"caller_role": ROLE}, {"HUB_ENTRY_SECRET": "s3cret"})
check("entry loads with defaults", entry is not None and entry["identity_header"] == "x-caller-arn"
      and entry["secret_header"] == "x-mcp-hub-entry-secret" and entry["allowed_actors"] == set())
check("the caller role's session is the actor", mod.entry_actor(GOOD, entry) == (None, "agent-0123abcd"))
check("dev-workbench session accepted",
      mod.entry_actor({**GOOD, "x-caller-arn": f"arn:aws:sts::{ACCOUNT}:assumed-role/{ROLE}/dev-workbench"}, entry)
      == (None, "dev-workbench"))

for name, headers, why in (
    ("wrong secret", {**GOOD, "x-mcp-hub-entry-secret": "s3cret "}, "secret"),
    ("empty secret", {**GOOD, "x-mcp-hub-entry-secret": ""}, "secret"),
    ("no identity header", {"x-mcp-hub-entry-secret": "s3cret"}, "assumed-role"),
    ("iam role arn, not a session", {**GOOD, "x-caller-arn": f"arn:aws:iam::{ACCOUNT}:role/{ROLE}"}, "assumed-role"),
    ("another role's session", {**GOOD, "x-caller-arn": f"arn:aws:sts::{ACCOUNT}:assumed-role/agent-platform-sdk-role/agent-0123abcd"}, "caller role"),
    ("extra path segment", {**GOOD, "x-caller-arn": f"{ARN}/x"}, "assumed-role"),
    ("user arn", {**GOOD, "x-caller-arn": f"arn:aws:iam::{ACCOUNT}:user/alice"}, "assumed-role"),
):
    reason, actor = mod.entry_actor(headers, entry)
    check(f"refused: {name}", bool(reason) and why in reason and actor is None, reason or "accepted")

strict = mod.load_entry_identity({"caller_role": ROLE, "allowed_actors": ["dev-workbench"]}, {"HUB_ENTRY_SECRET": "s3cret"})
reason, actor = mod.entry_actor(GOOD, strict)
check("allowlist: unregistered actor refused", bool(reason) and "not registered" in reason and actor is None, reason or "")

check("no block = entry off", mod.load_entry_identity(None, {"HUB_ENTRY_SECRET": "s"}) is None)
check("no secret in the environment = entry off (never open)", mod.load_entry_identity({"caller_role": ROLE}, {}) is None)
check("custom secret env name honoured",
      mod.load_entry_identity({"caller_role": ROLE, "secret_env": "X"}, {"X": "v"}) is not None)
try:
    mod.load_entry_identity({"secret_env": "X"}, {"X": "v"})
    check("caller_role required", False, "loaded without caller_role")
except SystemExit:
    check("caller_role required", True)

class _Log:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def warning(self, msg: str, *args) -> None:
        self.lines.append(msg % args if args else msg)


_log = _Log()
_disabled = mod.load_entry_identity({"caller_role": ROLE, "secret_env": "HUB_CUSTOM_ENTRY_VALUE"}, {}, log=_log)
check("empty secret disables the entry and warns once", _disabled is None and len(_log.lines) == 1)
check("the warning names no environment variable or value",
      bool(_log.lines) and "HUB_CUSTOM_ENTRY_VALUE" not in _log.lines[0] and "HUB_ENTRY_SECRET" not in _log.lines[0],
      _log.lines[0] if _log.lines else "no warning")

# ---------------- trust: network + callers (pod-to-pod under IRSA) ----------------
# No shared secret: the hub's listener is reachable only via the gateway's NLB,
# so the identity header alone is judged. An IRSA session name is generated by
# the SDK, so the ROLE names the application.

FRONT = "mcp-frontend"
FRONT_ROLE_ARN = f"arn:aws:iam::{ACCOUNT}:role/{FRONT}"
IRSA_ARN = f"arn:aws:sts::{ACCOUNT}:assumed-role/{FRONT}/botocore-session-1762650000"
net_cfg = {"trust": "network", "require_user_token": False,
           "callers": [{"role_arn": FRONT_ROLE_ARN, "actor": "frontend-app"}]}
net = mod.load_entry_identity(net_cfg, {})
check("network mode loads with no secret in the environment", net is not None and net["secret"] == "")
check("network mode: require_user_token honoured", net is not None and net["require_user_token"] is False)
check("network mode: an IRSA session of a registered role is its actor",
      mod.entry_actor({"x-caller-arn": IRSA_ARN}, net) == (None, "frontend-app"))
check("network mode: any session name of that role maps to the same actor",
      mod.entry_actor({"x-caller-arn": f"arn:aws:sts::{ACCOUNT}:assumed-role/{FRONT}/agent-evil"}, net)
      == (None, "frontend-app"))
check("network mode: a role path in role_arn is accepted and matched by name",
      mod.entry_actor({"x-caller-arn": IRSA_ARN},
                      mod.load_entry_identity({**net_cfg, "callers": [{"role_arn": f"arn:aws:iam::{ACCOUNT}:role/apps/{FRONT}", "actor": "frontend-app"}]}, {}))
      == (None, "frontend-app"))
check("network mode: the request is judged as an entry request on the identity header alone",
      mod.is_entry_request({"x-caller-arn": IRSA_ARN}, net))
check("network mode: a stray secret header still lands in the entry branch",
      mod.is_entry_request({"x-mcp-hub-entry-secret": "x"}, net))
check("network mode: a plain Bearer call is not an entry request", not mod.is_entry_request({"authorization": "Bearer x"}, net))
check("secret mode: the identity header alone is NOT an entry request (falls to Bearer/HMAC, which ignore it)",
      not mod.is_entry_request({"x-caller-arn": ARN}, entry))

OTHER_ACCOUNT = "1" * 12
for name, arn, why in (
    ("same role name in another account", f"arn:aws:sts::{OTHER_ACCOUNT}:assumed-role/{FRONT}/s", "registered caller"),
    ("same role name in another partition", f"arn:aws-cn:sts::{ACCOUNT}:assumed-role/{FRONT}/s", "registered caller"),
    ("an unregistered role", f"arn:aws:sts::{ACCOUNT}:assumed-role/mcp-intruder/s", "registered caller"),
    ("role-name prefix of a registered role", f"arn:aws:sts::{ACCOUNT}:assumed-role/{FRONT}-x/s", "registered caller"),
    ("the role ARN itself, not a session", FRONT_ROLE_ARN, "assumed-role"),
    ("an IAM user", f"arn:aws:iam::{ACCOUNT}:user/{FRONT}", "assumed-role"),
    ("a federated user", f"arn:aws:sts::{ACCOUNT}:federated-user/{FRONT}", "assumed-role"),
    ("empty identity header", "", "assumed-role"),
    ("trailing newline", IRSA_ARN + "\n", "assumed-role"),
    ("extra path segment", IRSA_ARN + "/x", "assumed-role"),
    ("two ARNs glued with a comma", f"{IRSA_ARN},{IRSA_ARN}", "assumed-role"),
):
    reason, actor = mod.entry_actor({"x-caller-arn": arn}, net)
    check(f"network mode refused: {name}", bool(reason) and why in reason and actor is None, reason or "accepted")

reason, actor = mod.entry_actor({"x-caller-arn": IRSA_ARN},
                                mod.load_entry_identity({**net_cfg, "allowed_actors": ["someone-else"]}, {}))
check("network mode: allowed_actors still applies to callers", bool(reason) and "not registered" in reason and actor is None)

both = mod.load_entry_identity({**net_cfg, "caller_role": ROLE}, {})
check("callers and caller_role together: callers first",
      mod.entry_actor({"x-caller-arn": IRSA_ARN}, both) == (None, "frontend-app"))
check("callers and caller_role together: caller_role session still works",
      mod.entry_actor({"x-caller-arn": ARN}, both) == (None, "agent-0123abcd"))
check("callers alone: a caller_role-shaped session is refused",
      mod.entry_actor({"x-caller-arn": ARN}, net)[1] is None)

_sec_callers = mod.load_entry_identity({"callers": net_cfg["callers"]}, {"HUB_ENTRY_SECRET": "s3cret"})
check("callers also work in secret mode, secret still required",
      mod.entry_actor({"x-caller-arn": IRSA_ARN, "x-mcp-hub-entry-secret": "s3cret"}, _sec_callers) == (None, "frontend-app")
      and mod.entry_actor({"x-caller-arn": IRSA_ARN}, _sec_callers)[1] is None)
check("require_user_token defaults to true", entry["require_user_token"] is True
      and mod.load_entry_identity({"trust": "network", "caller_role": ROLE}, {})["require_user_token"] is True)

for name, cfg in (
    ("unknown trust mode", {**net_cfg, "trust": "none"}),
    ("trust mode with odd case", {**net_cfg, "trust": "Network"}),
    ("neither caller_role nor callers", {"trust": "network"}),
    ("callers entry is not a mapping", {**net_cfg, "callers": [FRONT_ROLE_ARN]}),
    ("callers role_arn is a session ARN", {**net_cfg, "callers": [{"role_arn": IRSA_ARN, "actor": "a"}]}),
    ("callers role_arn has a wildcard", {**net_cfg, "callers": [{"role_arn": f"arn:aws:iam::{ACCOUNT}:role/*", "actor": "a"}]}),
    ("callers actor empty", {**net_cfg, "callers": [{"role_arn": FRONT_ROLE_ARN, "actor": ""}]}),
    ("callers actor with a slash", {**net_cfg, "callers": [{"role_arn": FRONT_ROLE_ARN, "actor": "a/b"}]}),
    ("one role mapped to two actors", {**net_cfg, "callers": [{"role_arn": FRONT_ROLE_ARN, "actor": "a"},
                                                              {"role_arn": FRONT_ROLE_ARN, "actor": "b"}]}),
    ("require_user_token as a string", {**net_cfg, "require_user_token": "false"}),
):
    try:
        mod.load_entry_identity(cfg, {})
        check(f"config refused: {name}", False, "loaded")
    except SystemExit:
        check(f"config refused: {name}", True)

print(f"\n{'FAILED: ' + ', '.join(failures) if failures else 'all passed'}")
assert not failures, f"entry identity checks failed: {failures}"
